def decrypt_ppcs(seeds, data):
    out = bytearray(len(data))
    out[0] = PPCS_TABLE[seeds[0]] ^ data[0]
    fb = data[0]
    for i in range(1, len(data)):
        out[i] = PPCS_TABLE[(seeds[fb & 3] + fb) & 0xff] ^ data[i]
        fb = data[i]
    return bytes(out)

VALID_TYPES = {0xD0, 0xD1, 0xE0, 0xE1, 0x42, 0x43}

with open('/tmp/aqara_talk.pcap', 'rb') as f:
    hdr = f.read(24)
    magic, = struct.unpack('<I', hdr[:4])
    endian = '<' if magic == 0xa1b2c3d4 else '>'

    sample_pkts = []
    while len(sample_pkts) < 20:
        b = f.read(16)
        if len(b) < 16: break
        ts_sec, ts_usec, incl_len, orig_len = struct.unpack(endian + 'IIII', b)
        data = f.read(incl_len)
        if len(data) >= 42 and data[42] == 0x83:
            sample_pkts.append(data[42:])

print(f"Sample pkts starting with 0x83: {len(sample_pkts)}")

s0 = 193
s1 = (-s0) & 0xff

found = []
for s2 in range(256):
    for s3 in range(256):
        seeds = [s0, s1, s2, s3]
        valid = True
        for pkt in sample_pkts[:10]:
            dec = decrypt_ppcs(seeds, pkt[:4])
            if dec[0] != 0xF1 or dec[1] not in VALID_TYPES:
                valid = False
                break
            p_len = (dec[2] << 8) | dec[3]
            if p_len != len(pkt) - 4:
                valid = False
                break
        if valid:
            found.append(seeds)

print(f"Found {len(found)} candidate seed sets: {found}")
if found:
    seeds = found[0]
    for i, p in enumerate(sample_pkts[:10]):
        dec = decrypt_ppcs(seeds, p)
        drw_hdr = dec[4:8] if len(dec) >= 8 else b''
        chan = drw_hdr[1] if len(drw_hdr) >= 2 else -1
        seq = (drw_hdr[2] << 8) | drw_hdr[3] if len(drw_hdr) >= 4 else -1
        print(f"Pkt {i} (len={len(p)}): PPPP type=0x{dec[1]:02x} | DRW chan={chan} seq={seq} | payload_hex={dec[8:24].hex()}")
