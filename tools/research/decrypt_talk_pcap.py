seeds = [165, 28, 11, 89]

def decrypt_ppcs(data):
    if not data: return b''
    out = bytearray(len(data))
    out[0] = PPCS_TABLE[seeds[0]] ^ data[0]
    fb = data[0]
    for i in range(1, len(data)):
        out[i] = PPCS_TABLE[(seeds[fb & 3] + fb) & 0xff] ^ data[i]
        fb = data[i]
    return bytes(out)

pcap_file = '/tmp/aqara_talk.pcap'
cam_ip = '192.168.5.48'

with open(pcap_file, 'rb') as f:
    hdr = f.read(24)
    magic, = struct.unpack('<I', hdr[:4])
    endian = '<' if magic == 0xa1b2c3d4 else '>'

    pkts = []
    while True:
        b = f.read(16)
        if len(b) < 16: break
        ts_sec, ts_usec, incl_len, orig_len = struct.unpack(endian + 'IIII', b)
        data = f.read(incl_len)
        if len(data) < 42: continue
        ip_hdr = data[14:34]
        if ip_hdr[9] != 17: continue
        src_ip = '.'.join(map(str, ip_hdr[12:16]))
        dst_ip = '.'.join(map(str, ip_hdr[16:20]))
        udp_payload = data[42:]
        if src_ip == cam_ip or dst_ip == cam_ip:
            pkts.append({
                'ts': ts_sec + ts_usec / 1e6,
                'dir': 'APP->CAM' if dst_ip == cam_ip else 'CAM->APP',
                'payload': udp_payload
            })

t0 = pkts[0]['ts'] if pkts else 0

for i, p in enumerate(pkts[:40]):
    dec = decrypt_ppcs(p['payload'])
    if len(dec) < 8: continue
    drw_payload = dec[4:]
    marker = drw_payload[0]
    chan = drw_payload[1]
    seq = (drw_payload[2] << 8) | drw_payload[3]
    body = drw_payload[4:]
    rel_ts = p['ts'] - t0
    print(f"Pkt {i:2d} [{rel_ts:8.3f}s] {p['dir']} | marker=0x{marker:02x} chan={chan} seq={seq} | body={body[:12].hex()}")
